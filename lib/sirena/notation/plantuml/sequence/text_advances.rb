          # @return [Float] the widest line PlantUML draws for `text`
          def self.width(text, font_size:, bold: false)
            table = bold ? BOLD : PLAIN
            text.split(/\\n|\n/, -1).map do |line|
              line.each_char.sum do |char|
                units = table[char]
                next units * font_size / UNITS_PER_EM if units

                TextMeasurement.measure(char, font_size: font_size)[:width]
              end
            end.max.to_f
          end
        end
