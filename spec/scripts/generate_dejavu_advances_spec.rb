# frozen_string_literal: true

require "spec_helper"

# The generator needs the ttfunk gem, which is development-only and not in
# the bundle, so a stand-in TTFunk is stubbed and the script is read into a
# module of its own, keeping its top-level methods off Object.
RSpec.describe "scripts/generate_dejavu_advances.rb", :aggregate_failures,
               type: :task do
  let(:metrics) { Struct.new(:advances) }
  let(:fake_font) do
    Struct.new(:advances, :units) do
      def header = Struct.new(:units_per_em).new(units)

      def cmap = Struct.new(:unicode).new([advances.to_h { [_1, _1] }])

      def horizontal_metrics
        table = advances
        Struct.new(:table) do
          def for(glyph) = Struct.new(:advance_width).new(table.fetch(glyph))
        end.new(table)
      end
    end
  end
  let(:tool) do
    script = File.expand_path("../../scripts/generate_dejavu_advances.rb",
                              __dir__)
    mod = Module.new
    allow(mod).to receive(:require).with("ttfunk")
    mod.module_eval(File.read(script), script)
    Object.new.extend(mod)
  end

  before do
    stub_const("TTFunk", Module.new)
    stub_const("TTFunk::File", Class.new { def self.open(_path) = nil })
    fonts = {
      "regular.ttf" => fake_font.new({ 0x20 => 651, 0x41 => 1401,
                                       0x42 => 1405, 0x7A => 1075 }, 2048),
      "bold.ttf" => fake_font.new({ 0x20 => 713, 0x41 => 1585 }, 2048),
    }
    allow(TTFunk::File).to receive(:open) do |path|
      fonts.fetch(File.basename(path))
    end
  end

  it "reads each face's advances in design units" do
    expect(tool.faces("regular.ttf", "bold.ttf")).to eq(
      "REGULAR" => { 0x20 => 651, 0x41 => 1401, 0x42 => 1405, 0x7A => 1075 },
      "BOLD" => { 0x20 => 713, 0x41 => 1585 },
    )
  end

  it "skips a codepoint the font has no glyph for" do
    font = fake_font.new({ 0x41 => 1401 }, 2048)
    allow(font).to receive(:cmap)
      .and_return(Struct.new(:unicode).new([{ 0x41 => 0x41, 0x42 => 0 }]))

    expect(tool.advances(font, [0x41..0x43])).to eq(0x41 => 1401)
  end

  it "refuses a font that is not 2048 units to the em" do
    expect { tool.advances(fake_font.new({}, 1000)) }
      .to raise_error(SystemExit).and output(/2048 units/).to_stderr
  end

  it "joins consecutive codepoints into one run" do
    expect(tool.runs({ 0x41 => 1, 0x42 => 2, 0x44 => 4 }))
      .to eq([[0x41, [1, 2]], [0x44, [4]]])
  end

  describe "the rendered module" do
    let(:rendered) { tool.render(tool.faces("regular.ttf", "bold.ttf")) }

    let(:advances) do
      mod = Module.new
      mod.module_eval(rendered, "(generated)")
      mod::Sirena::TextMeasurement::DejaVuAdvances
    end

    it "parses back to per-mille advances" do
      expect(advances::REGULAR[0x41]).to eq(1401 * 1000 / 2048.0)
      expect(advances::BOLD[0x20]).to eq(713 * 1000 / 2048.0)
    end

    it "names its generator and lists runs by codepoint" do
      expect(rendered).to include(
        "GENERATED by scripts/generate_dejavu_advances.rb", "U+0041: 1401 1405"
      )
    end
  end
end
