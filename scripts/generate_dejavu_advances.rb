#!/usr/bin/env ruby
# frozen_string_literal: true

# Regenerates lib/sirena/text_measurement/dejavu_advances.rb from the hmtx
# tables of DejaVu Sans and DejaVu Sans Bold, the face Java's "SansSerif"
# resolves to on Linux and so the face a PlantUML server measures salt text
# with. DejaVu Fonts 2.37 is under the Bitstream Vera licence with public
# domain changes (https://dejavu-fonts.github.io/License.html): it allows
# use and redistribution, and only the advance widths, numeric facts about
# each glyph, are read here; no glyph outline or font file is shipped.
# Advances are kept in design units (2048 to the em): PlantUML sums them at
# full precision, and a per-mille rounding drifts by a tenth of a pixel
# over a table row.
# Development-only: `gem install ttfunk`, download the dejavu-fonts-ttf
# release from https://github.com/dejavu-fonts/dejavu-fonts, then plain
# `ruby`:
#
#   ruby scripts/generate_dejavu_advances.rb \
#     DejaVuSans.ttf DejaVuSans-Bold.ttf \
#     lib/sirena/text_measurement/dejavu_advances.rb
require "ttfunk"

RANGES = [0x20..0x7E, 0xA0..0x24F].freeze

def advances(font, ranges = RANGES)
  abort "expected 2048 units to the em" unless font.header.units_per_em == 2048

  ranges.flat_map(&:to_a).filter_map { |code| advance(font, code) }.to_h
end

def advance(font, code)
  glyph = font.cmap.unicode.first[code]
  return if glyph.nil? || glyph.zero?

  [code, font.horizontal_metrics.for(glyph).advance_width]
end

def runs(table)
  table.sort.each_with_object([]) do |(code, value), found|
    last = found.last
    if last && last[0] + last[1].length == code
      last[1] << value
    else
      found << [code, [value]]
    end
  end
end

def data_lines(runs)
  runs.flat_map do |start, values|
    values.each_slice(16).with_index.map do |slice, index|
      marker = index.zero? ? format("U+%04X: ", start) : ""
      "        #{marker}#{slice.join(' ')}\n"
    end
  end
end

def faces(regular, bold)
  { "REGULAR" => regular, "BOLD" => bold }.transform_values do |path|
    advances(TTFunk::File.open(path))
  end
end

def body(faces)
  faces.map do |constant, table|
    ["      #{constant}_DATA = <<~RUNS\n", *data_lines(runs(table)),
     "      RUNS\n"].join
  end.join("\n")
end

def render(faces)
  <<~HEADER + body(faces) + <<~FOOTER
    # frozen_string_literal: true

    # GENERATED by scripts/generate_dejavu_advances.rb; do not edit by hand.
    #
    # Horizontal advance widths of DejaVu Sans Regular and Bold, in design
    # units of a 2048-unit em, for Basic Latin and Latin-1 through Latin
    # Extended-B. Advances are numeric facts about a glyph, not a copy of any
    # font. Same layout as ArialAdvances::DATA; REGULAR and BOLD hold them
    # in per-mille em.
    module Sirena
      class TextMeasurement
        module DejaVuAdvances
  HEADER

          UNITS_PER_EM = 2048.0

          # codepoint => advance in per-mille em
          def self.parse(data)
            codepoint = 0
            data.each_line.with_object({}) do |line, table|
              start, values = split(line)
              codepoint = start.delete_prefix("U+").to_i(16) if start
              values.each do |value|
                table[codepoint] = value.to_i * 1000 / UNITS_PER_EM
                codepoint += 1
              end
            end.freeze
          end

          # A run's marker, if the line starts one, and its advances.
          def self.split(line)
            start, values = line.include?(":") ? line.split(":", 2) : [nil, line]
            [start, values.split]
          end

          REGULAR = parse(REGULAR_DATA)
          BOLD = parse(BOLD_DATA)
          private_class_method :parse, :split
        end
      end
    end
  FOOTER
end

if __FILE__ == $PROGRAM_NAME
  regular, bold, output = ARGV
  abort "usage: #{$PROGRAM_NAME} REGULAR.ttf BOLD.ttf OUTPUT.rb" unless output

  File.write("#{output}.tmp", render(faces(regular, bold)))
  File.rename("#{output}.tmp", output)
end
