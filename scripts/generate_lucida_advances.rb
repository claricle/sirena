#!/usr/bin/env ruby
# frozen_string_literal: true

# Regenerates lib/sirena/text_measurement/lucida_advances.rb from the hmtx
# tables of Lucida Grande Regular and Bold, the face Java's "SansSerif"
# resolves to on macOS and so the face PlantUML measured salt text with.
# Advances are kept in design units (2048 to the em): PlantUML sums them at
# full precision, and a per-mille rounding drifts by a tenth of a pixel
# over a table row.
# Development-only: `gem install ttfunk`, then plain `ruby`:
#
#   ruby scripts/generate_lucida_advances.rb \
#     /System/Library/Fonts/LucidaGrande.ttc \
#     lib/sirena/text_measurement/lucida_advances.rb
require "ttfunk"

RANGES = [0x20..0x7E, 0xA0..0x24F].freeze
FACES = { "Lucida Grande" => "REGULAR",
          "Lucida Grande Bold" => "BOLD" }.freeze

def advances(font, ranges = RANGES)
  abort "expected 2048 units to the em" unless font.header.units_per_em == 2048

  ranges.flat_map(&:to_a).filter_map { |code| advance(font, code) }.to_h
end

def advance(font, code)
  glyph = font.cmap.unicode.first[code]
  return if glyph.nil? || glyph.zero?

  [code, font.horizontal_metrics.for(glyph).advance_width]
end

def runs(table)
  table.sort.each_with_object([]) do |(code, value), found|
    last = found.last
    if last && last[0] + last[1].length == code
      last[1] << value
    else
      found << [code, [value]]
    end
  end
end

def data_lines(runs)
  runs.flat_map do |start, values|
    values.each_slice(16).with_index.map do |slice, index|
      marker = index.zero? ? format("U+%04X: ", start) : ""
      "        #{marker}#{slice.join(' ')}\n"
    end
  end
end

def faces(path)
  TTFunk::Collection.open(path) do |collection|
    collection.each_with_object({}) do |font, found|
      name = font.name.font_name.first
      found[FACES.fetch(name)] = advances(font) if FACES.key?(name)
    end
  end
end

def body(faces)
  faces.map do |constant, table|
    <<~FACE.gsub(/^(?=.)/, "      ") + data_lines(runs(table)).join + "      RUNS\n"
      #{constant}_DATA = <<~RUNS
    FACE
  end.join("\n")
end

def render(faces)
  <<~HEADER + body(faces) + <<~FOOTER
    # frozen_string_literal: true

    # GENERATED by scripts/generate_lucida_advances.rb; do not edit by hand.
    #
    # Horizontal advance widths of Lucida Grande Regular and Bold, in design
    # units of a 2048-unit em, for Basic Latin and Latin-1 through Latin
    # Extended-B. Advances are numeric facts about a glyph, not a copy of any
    # font. Same layout as ArialAdvances::DATA; REGULAR and BOLD hold them
    # in per-mille em.
    module Sirena
      class TextMeasurement
        module LucidaAdvances
  HEADER

          UNITS_PER_EM = 2048.0

          # codepoint => advance in per-mille em
          def self.parse(data)
            codepoint = 0
            data.each_line.with_object({}) do |line, table|
              start, values =
                line.include?(":") ? line.split(":", 2) : [nil, line]
              codepoint = start.delete_prefix("U+").to_i(16) if start
              values.split.each do |value|
                table[codepoint] = value.to_i * 1000 / UNITS_PER_EM
                codepoint += 1
              end
            end.freeze
          end

          REGULAR = parse(REGULAR_DATA)
          BOLD = parse(BOLD_DATA)
          private_class_method :parse
        end
      end
    end
  FOOTER
end

if __FILE__ == $PROGRAM_NAME
  source, output = ARGV
  abort "usage: #{$PROGRAM_NAME} LucidaGrande.ttc OUTPUT.rb" unless output

  File.write("#{output}.tmp", render(faces(source)))
  File.rename("#{output}.tmp", output)
end
